import { readFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import assert from 'node:assert/strict';

const script = readFileSync('scripts/cleanup-branches.mjs', 'utf8');
const workflow = readFileSync('.github/workflows/cleanup-branches.yml', 'utf8');
execFileSync(process.execPath, ['--check', 'scripts/cleanup-branches.mjs'], { stdio: 'ignore' });

assert.match(script, /const defaultBranch = repoInfo\.default_branch \|\| 'main'/);
assert.match(script, /const expectedRef = 'refs\/heads\/' \+ defaultBranch/);
assert.match(script, /process\.env\.GITHUB_ACTIONS !== 'true'/);
assert.match(script, /process\.env\.GITHUB_REF !== expectedRef/);
assert.match(script, /const maxDeletions = Number\(process\.env\.CLEANUP_MAX_DELETIONS \|\| 25\)/);
assert.match(script, /maxDeletions < 1/);
assert.match(script, /if \(!Number\.isFinite\(record\.date\)\)/);
assert.match(script, /\.filter\(record => record\.name !== defaultBranch\)/);
assert.match(script, /\.filter\(record => record\.name !== 'main'\)/);
assert.match(script, /\.filter\(record => !active\.has\(record\.name\)\)/);
assert.match(script, /\.filter\(record => !candidates\.includes\(record\.name\)\)/);
assert.match(script, /\.filter\(record => !record\.branchProtected\)/);
assert.match(script, /pr\.base\?\.ref !== defaultBranch/);
assert.match(script, /pr\.merge_commit_sha == null/);
assert.match(script, /const repositoryOwnerLogin = repoInfo\.owner\?\.login \?\? repository\.split\('\/'\)\[0\]/);
assert.match(script, /const headRepoId = pr\.head\?\.repo\?\.id \?\? null/);
assert.match(script, /const sameRepositoryHead = headRepoId != null/);
assert.match(script, /pr\.head\?\.label === repositoryOwnerLogin \+ ':' \+ pr\.head\.ref/);
assert.match(script, /record\.branchTipSha !== record\.mergeHeadSha/);
assert.match(script, /const mergedRecords = \[\.\.\.mergedByHead\.values\(\)\]/);
assert.match(script, /Merged PR cleanup candidates before age\/SHA checks/);
assert.match(script, /mergeHeadSha/);
assert.match(script, /branchTipSha/);
assert.match(script, /.filter\(record => record\.branchTipSha != null\)/);
assert.match(script, /record\.branchTipSha !== record\.mergeHeadSha/);
assert.match(script, /const mergedMaxAgeDays = Number\(process\.env\.CLEANUP_MERGED_MAX_AGE_DAYS \|\| 7\)/);
assert.match(script, /CLEANUP_MERGED_BRANCHES === 'true'/);
assert.match(script, /if \(dryRun\)/);
assert.match(script, /method: 'DELETE'/);
assert.match(script, /deleted \+ mergedDeleted >= maxDeletions/);
assert.match(workflow, /push:\s*\n\s+branches:\s*\n\s+- main/);
assert.match(workflow, /if: github\.ref == 'refs\/heads\/main'/);
assert.match(workflow, /contents: write/);
assert.match(workflow, /pull-requests:\s+read/);
assert.match(workflow, /CLEANUP_MERGED_BRANCHES: 'true'/);
assert.match(workflow, /CLEANUP_MERGED_MAX_AGE_DAYS: '7'/);
assert.match(workflow, /CLEANUP_MAX_DELETIONS: '50'/);
assert.match(workflow, /inputs:\s*\n\s+dry_run:/);
assert.match(workflow, /CLEANUP_DRY_RUN:/);

console.log('Branch cleanup safety contract: PASS');
